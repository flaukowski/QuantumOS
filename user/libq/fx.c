int32_t fx_sin(uint32_t turns) {
    return fx_sin_q15[(turns >> 24) & 255u];
}

int32_t fx_cos(uint32_t turns) {
    /* cos = sin shifted a quarter turn (+64 in the top byte). */
    return fx_sin_q15[((turns >> 24) + 64u) & 255u];
}

/* floor(sqrt(x)) for x up to 2^64-1, digit-by-digit in base 2 (no float). */
uint32_t fx_isqrt(uint64_t x) {
    uint64_t rem = x;
    uint64_t root = 0;
    uint64_t bit = (uint64_t)1 << 62; /* highest power of 4 <= 2^63 */
    while (bit > rem) {
        bit >>= 2;
    }
    while (bit != 0) {
        if (rem >= root + bit) {
            rem -= root + bit;
            root = (root >> 1) + bit;
        } else {
            root >>= 1;
        }
        bit >>= 2;
    }
    return (uint32_t)root;
}
